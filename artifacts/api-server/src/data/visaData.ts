export function getDefaultEntry(passport: string, destination: string): VisaEntry {
  if (passport === destination) {
    return { requirement: "visa_free", maxStay: "unlimited", notes: "You are a citizen of this country" };
  }

  // Primary source: authoritative Passport Index dataset (ilyankou/passport-index-dataset)
  const indexEntry = getVisaEntryFromIndex(passport, destination);
  if (indexEntry) return indexEntry;

  // Fallback: hand-coded matrix for any remaining gap
  const entry = visaMatrix[passport]?.[destination];
  if (entry) return entry;

  return { requirement: "visa_required", notes: "Verify requirements with the destination country embassy" };
}
